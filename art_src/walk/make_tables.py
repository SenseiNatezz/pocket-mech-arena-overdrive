"""Builds assets/sprites/walk/walk_tables.gd from the art_src/walk/<sheet>.json files that
art_src/halo_forge/tools/render_walk.py writes (one per two-layer mech).

  py -3 art_src/walk/make_tables.py

WalkTables.TABLES[<sheet>] = {"fist": [...8], "fist_left": [...8], "tip": [...8]}: how far the right fist, the
left fist and the rifle tip sit from their first-idle-frame spot in each frame of the upper body's `walk` row,
in sheet px (player/weapons/held_weapon.gd adds them, so held weapons stay in the hands as the arms swing).
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "assets", "sprites", "walk", "walk_tables.gd")

lines = [
    "class_name WalkTables",
    "extends RefCounted",
    "## GENERATED by art_src/walk/make_tables.py from art_src/walk/*.json (render_walk.py) - do not edit.",
    "## Per two-layer mech: the right fist's, left fist's and rifle tip's offset from the first idle frame in each",
    "## of the 8 frames of the upper body's `walk` row, in sheet px (player/weapons/held_weapon.gd).",
    "",
    "const TABLES := {",
]
for path in sorted(glob.glob(os.path.join(HERE, "*.json"))):
    d = json.load(open(path))
    lines.append('\t"%s": {' % d["name"])
    for key in ("fist", "fist_left", "tip"):
        pts = ", ".join("Vector2(%.1f, %.1f)" % (p[0], p[1]) for p in d["delta"][key])
        lines.append('\t\t"%s": [%s],' % (key, pts))
    lines.append("\t},")
lines.append("}")
with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("WROTE", os.path.normpath(OUT))
