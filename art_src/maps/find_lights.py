"""Finds the light sources PAINTED on each top-down map (lamps, lava, crystals, beacons, neon) and writes
environment/map_lights.gd, so the game can make them pulse / flicker / blink (environment/map_life.gd).

  py -3 art_src/maps/find_lights.py [preview dir]

A spot counts as a light when it is bright, coloured, and clearly brighter than the area round it. Per light:
[x, y (map px), radius (map px), r, g, b, kind]; kind 0 = slow pulse, 1 = fire flicker (orange: lava, furnaces),
2 = blink (small red beacons). With a preview dir it also saves <map>_lights.jpg with the lights circled.
"""
import colorsys, os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
MAPS = ["arctic", "jungle", "outpost", "skyway", "plaza", "forge", "desert", "dock"]
CELL = 8
MAX_LIGHTS = {"default": 70, "desert": 0, "dock": 40, "arctic": 40, "jungle": 30}
# Daylight maps: only real lamps count there (sunlit rock, snow and yellow machinery are bright and coloured
# too). "warm" = red..yellow hues only, "red" = the red beacons only.
HUES = {"arctic": "warm", "jungle": "lamp", "dock": "red"}
MIN_GAP = 7  # cells between two lights

out = ["class_name MapLights", "extends RefCounted",
       "## GENERATED by art_src/maps/find_lights.py - do not edit. The lights painted on each map:",
       "## [x, y (map px), radius (map px), r, g, b, kind (0 pulse, 1 fire flicker, 2 blink)].", "",
       "const TABLES := {"]
for name in MAPS:
    path = os.path.join(ROOT, "assets", "hq", "env_%s_topdown.png" % name)
    im = Image.open(path).convert("RGB")
    w, h = im.size[0] // CELL, im.size[1] // CELL
    a = np.asarray(im, dtype=np.float32)[:h * CELL, :w * CELL] / 255.0
    a = a.reshape(h, CELL, w, CELL, 3).mean(axis=(1, 3))
    v = a.max(axis=2)
    s = (v - a.min(axis=2)) / np.maximum(v, 1e-4)
    local = np.asarray(Image.fromarray((v * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(14)), dtype=np.float32) / 255.0
    rise = v - local
    mx, mn = v, a.min(axis=2)
    d = np.maximum(mx - mn, 1e-4)
    hue = np.where(mx == a[..., 0], ((a[..., 1] - a[..., 2]) / d) % 6.0,
                   np.where(mx == a[..., 1], (a[..., 2] - a[..., 0]) / d + 2.0, (a[..., 0] - a[..., 1]) / d + 4.0)) / 6.0
    ok = (v > 0.6) & (s > 0.3) & (rise > 0.15)
    want = HUES.get(name, "any")
    if want == "warm":
        ok = (v > 0.6) & (rise > 0.12) & ((hue < 0.16) | (hue > 0.94)) & (s > 0.2)
    elif want == "lamp":
        ok &= (hue > 0.02) & (hue < 0.115) & (s > 0.55)
    elif want == "red":
        ok = (v > 0.5) & (s > 0.5) & (rise > 0.05) & ((hue < 0.03) | (hue > 0.93))
    score = np.where(ok, rise * (0.4 + s), 0.0)
    order = np.argsort(score, axis=None)[::-1]
    picked = []
    for idx in order:
        y, x = divmod(int(idx), w)
        if score[y, x] <= 0.0 or len(picked) >= MAX_LIGHTS.get(name, MAX_LIGHTS["default"]):
            break
        if any((x - px) ** 2 + (y - py) ** 2 < MIN_GAP ** 2 for px, py, *_ in picked):
            continue
        y0, y1, x0, x1 = max(y - 4, 0), min(y + 5, h), max(x - 4, 0), min(x + 5, w)
        size = int(ok[y0:y1, x0:x1].sum())
        r, g, b = (float(c) for c in a[y, x])
        hh, ss, vv = colorsys.rgb_to_hsv(r, g, b)
        r, g, b = colorsys.hsv_to_rgb(hh, min(ss * 1.25, 1.0), 1.0)
        kind = 0
        if (hh < 0.035 or hh > 0.94) and ss > 0.55 and size <= 6:
            kind = 2
        elif 0.02 <= hh <= 0.115 and ss > 0.5:
            kind = 1
        if want == "red":
            kind = 2
        radius = min(60 + 9 * size, 190)
        picked.append((x, y, radius, r, g, b, kind))
    rows = ", ".join("[%d, %d, %d, %.2f, %.2f, %.2f, %d]" % (x * CELL + CELL // 2, y * CELL + CELL // 2, rad, r, g, b, k)
                     for x, y, rad, r, g, b, k in picked)
    out.append('\t"%s": [%s],' % (name, rows))
    print(name, len(picked), "lights;", sum(1 for p in picked if p[6] == 1), "fire,", sum(1 for p in picked if p[6] == 2), "blink")
    if len(sys.argv) > 1:
        pv = im.resize((w * 2, h * 2))
        d = ImageDraw.Draw(pv)
        for x, y, rad, r, g, b, k in picked:
            rr = rad / CELL * 2 * 0.5
            d.ellipse((x * 2 - rr, y * 2 - rr, x * 2 + rr, y * 2 + rr), outline=[(255, 255, 255), (255, 160, 0), (255, 0, 0)][k], width=2)
        pv.save(os.path.join(sys.argv[1], "%s_lights.jpg" % name), quality=80)
out += ["}", ""]
open(os.path.join(ROOT, "environment", "map_lights.gd"), "w", newline="\n").write("\n".join(out))
print("WROTE environment/map_lights.gd")
